# Day 1: Vehicle Speed and Distance Calculator

speed_kmh = 72.0
time_s = 20.0

speed_ms = speed_kmh / 3.6
distance_m = speed_ms * time_s

print("Vehicle speed:", speed_kmh, "km/h")
print("Vehicle speed:", speed_ms, "m/s")
print("Travel time:", time_s, "s")
print("Travel distance:", distance_m, "m")